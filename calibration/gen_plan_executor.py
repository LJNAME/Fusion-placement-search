"""从 validation_plans.json 生成真机可执行的 HIP 执行器。

执行器语义与仿真器的事件队列对齐：
  - 每个融合组 = 一台设备 stream 上按序执行的一组 kernel；
  - 组依赖：同设备前驱等组事件，跨设备前驱等拷贝完成事件；
  - 跨设备边 = hipMemcpyAsync D2D；
  - 记录墙钟 makespan + 逐卡峰值显存（hipMemGetInfo 采样）。

所以"组合层"（调度顺序、通信-计算重叠、争用、显存生命周期）第一次被
真机检验；仿真器与真机的分歧就是组合层校准要修的。

运行：
  python calibration/gen_plan_executor.py \
      --plans validation_plans.json --out build/plan_executor_hip.cpp --n-gpus 4
编译（ROCm 环境）：
  hipcc -O2 -o build/plan_executor_hip build/plan_executor_hip.cpp -lrocblas
"""

from __future__ import annotations

import argparse
import json
import os
from typing import Dict, List


HEADER = r"""// generated by gen_plan_executor.py — do not edit
#include <hip/hip_runtime.h>
#include <rocblas/rocblas.h>
#include <atomic>
#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <thread>

static void chk(hipError_t e) {
  if (e != hipSuccess) {
    fprintf(stderr, "[exec] HIP error %d: %s\n", (int)e, hipGetErrorString(e));
    exit(1);
  }
}
static void chk_r(rocblas_status s) {
  if (s != rocblas_status_success) {
    fprintf(stderr, "[exec] rocblas error %d\n", (int)s);
    exit(1);
  }
}

__global__ void empty_kernel(int dummy) {}

__global__ void pass_kernel(const float* a, float* c, int n) {
  int i = blockIdx.x * blockDim.x + threadIdx.x;
  if (i < n) c[i] = a[i];
}
__global__ void add_kernel(const float* a, const float* b, float* c, int n) {
  int i = blockIdx.x * blockDim.x + threadIdx.x;
  if (i < n) c[i] = a[i] + b[i];
}
__global__ void scale_kernel(const float* a, float s, float* c, int n) {
  int i = blockIdx.x * blockDim.x + threadIdx.x;
  if (i < n) c[i] = a[i] * s;
}
__global__ void gelu_kernel(const float* a, float* c, int n) {
  int i = blockIdx.x * blockDim.x + threadIdx.x;
  if (i < n) c[i] = 0.5f * a[i] * (1.0f + erff(a[i] * 0.70710678118f));
}
__global__ void layernorm_kernel(const float* a, float* c, int n, int rows) {
  extern __shared__ float sdata[];
  int row = blockIdx.x;
  if (row >= rows) return;
  const float* x = a + (size_t)row * n;
  float* y = c + (size_t)row * n;
  int tid = threadIdx.x, nthreads = blockDim.x;
  float lsum = 0.f, lsq = 0.f;
  for (int i = tid; i < n; i += nthreads) {
    float v = x[i]; lsum += v; lsq += v * v;
  }
  sdata[tid] = lsum; __syncthreads();
  for (int s = nthreads / 2; s > 0; s >>= 1) {
    if (tid < s) sdata[tid] += sdata[tid + s]; __syncthreads();
  }
  float sum = sdata[0]; __syncthreads();
  sdata[tid] = lsq; __syncthreads();
  for (int s = nthreads / 2; s > 0; s >>= 1) {
    if (tid < s) sdata[tid] += sdata[tid + s]; __syncthreads();
  }
  float sq = sdata[0];
  float mean = sum / n;
  float inv = 1.0f / sqrtf(sq / n - mean * mean + 1e-5f);
  for (int i = tid; i < n; i += nthreads) y[i] = (x[i] - mean) * inv;
}
__global__ void softmax_kernel(const float* a, float* c, int n, int rows) {
  extern __shared__ float sdata[];
  int row = blockIdx.x;
  if (row >= rows) return;
  const float* x = a + (size_t)row * n;
  float* y = c + (size_t)row * n;
  int tid = threadIdx.x, nthreads = blockDim.x;
  float mx = -1e30f;
  for (int i = tid; i < n; i += nthreads) mx = fmaxf(mx, x[i]);
  sdata[tid] = mx; __syncthreads();
  for (int s = nthreads / 2; s > 0; s >>= 1) {
    if (tid < s) sdata[tid] = fmaxf(sdata[tid], sdata[tid + s]); __syncthreads();
  }
  mx = sdata[0]; __syncthreads();
  float ls = 0.f;
  for (int i = tid; i < n; i += nthreads) ls += expf(x[i] - mx);
  sdata[tid] = ls; __syncthreads();
  for (int s = nthreads / 2; s > 0; s >>= 1) {
    if (tid < s) sdata[tid] += sdata[tid + s]; __syncthreads();
  }
  float inv = 1.0f / sdata[0]; __syncthreads();
  for (int i = tid; i < n; i += nthreads) y[i] = expf(x[i] - mx) * inv;
}
"""


def _shape(node: dict) -> dict:
    return node.get("extra", {}).get("shape") or {}


def _elem_n(node: dict) -> int:
    sh = _shape(node)
    n = sh.get("n")
    if n and float(n) > 0:
        return int(n)
    return max(int(node.get("out_bytes", 0)) // 4, 1)


def _gen_plan(idx: int, entry: dict, n_devs: int) -> List[str]:
    g = entry["graph"]
    p = entry["plan"]
    name = entry["name"].replace('"', "'")
    nodes = {nd["id"]: nd for nd in g["nodes"]}
    node_ids = list(nodes.keys())
    edges = g["edges"]
    groups = p["groups"]

    node_group: Dict[str, int] = {}
    for gi, grp in enumerate(groups):
        for nid in grp["node_ids"]:
            node_group[nid] = gi
    group_dev = [grp["device"] for grp in groups]

    # 跨设备边 -> 拷贝索引
    cross = []
    for e in edges:
        sg, dg = node_group[e["src"]], node_group[e["dst"]]
        if group_dev[sg] != group_dev[dg]:
            cross.append(
                {
                    "idx": len(cross),
                    "src": e["src"],
                    "dst": e["dst"],
                    "bytes": int(e.get("bytes") or nodes[e["src"]]["out_bytes"]),
                    "sg": sg,
                    "dg": dg,
                    "sdev": group_dev[sg],
                    "ddev": group_dev[dg],
                }
            )
    in_cross: Dict[int, List[int]] = {gi: [] for gi in range(len(groups))}
    out_cross: Dict[int, List[int]] = {gi: [] for gi in range(len(groups))}
    for c in cross:
        in_cross[c["dg"]].append(c["idx"])
        out_cross[c["sg"]].append(c["idx"])

    last_consumer: Dict[str, int] = {}
    for nid in node_ids:
        cons = [node_group[e["dst"]] for e in edges if e["src"] == nid]
        last_consumer[nid] = max(cons) if cons else -1

    n_nodes = len(node_ids)
    n_groups = len(groups)
    n_cross = len(cross)
    nn = n_nodes

    def input_buf(nid: str, edge: dict) -> str:
        # 只有真正跨设备的边才走 recv；同设备（含同组/异组）直接读源节点输出
        for c in cross:
            if c["src"] == edge["src"] and c["dst"] == nid:
                return f"recv[{c['idx']}]"
        return f"out[{node_ids.index(edge['src'])}]"

    def in_elem(nid: str, edge: dict) -> int:
        # 输入张量的元素数（跨设备读 recv 大小，否则读源节点输出大小）
        for c in cross:
            if c["src"] == edge["src"] and c["dst"] == nid:
                return max(int(c["bytes"]) // 4, 1)
        return max(int(nodes[edge["src"]].get("out_bytes", 0)) // 4, 1)

    L: List[str] = []
    L.append(f"static void run_plan_{idx}(rocblas_handle* rb, int n_devs) {{")
    L.append(f'  fprintf(stderr, "[exec] plan {idx}: {name}\\n");')
    L.append(f"  const int NN = {nn}, NG = {n_groups}, NC = {n_cross};")
    L.append("  float* out[NN]; float* param[NN]; float* recv[NC];")
    L.append("  hipStream_t streams[n_devs]; hipEvent_t ev_g[NG], ev_c[NC];")
    L.append('  bool probe = getenv("EXEC_MEM_PROBE") != nullptr;')
    L.append('  bool empty = getenv("EXEC_EMPTY_KERNELS") != nullptr;')
    L.append(f"  bool out_freed[{nn}]; for (int i = 0; i < {nn}; i++) out_freed[i] = false;")
    L.append(f"  bool recv_freed[{n_cross}]; for (int i = 0; i < {n_cross}; i++) recv_freed[i] = false;")
    # stream/event 必须按设备创建：HIP 的流和事件属于创建时的当前设备
    L.append("  for (int d = 0; d < n_devs; d++) { hipSetDevice(d); hipStreamCreate(&streams[d]); }")
    for gi, grp in enumerate(groups):
        L.append(f"  hipSetDevice({group_dev[gi]}); hipEventCreate(&ev_g[{gi}]);")
    for c in cross:
        L.append(f"  hipSetDevice({c['sdev']}); hipEventCreate(&ev_c[{c['idx']}]);")
    L.append("  hipSetDevice(0);")
    L.append(f'  fprintf(stderr, "[exec] plan {idx} setup: streams+events done\\n");')
    L.append("  if (!probe) {")
    for i, nid in enumerate(node_ids):
        nd = nodes[nid]
        dev = group_dev[node_group[nid]]
        sz = max(int(nd.get("out_bytes", 0)), 4)
        L.append(f"    hipSetDevice({dev});")
        L.append(f"    chk(hipMalloc(&out[{i}], {sz}));")
        pb = int(nd.get("param_bytes", 0))
        if pb > 0:
            L.append(f"    chk(hipMalloc(&param[{i}], {pb}));")
        else:
            L.append(f"    param[{i}] = nullptr;")
    for c in cross:
        L.append(f"    hipSetDevice({c['ddev']});")
        L.append(f"    chk(hipMalloc(&recv[{c['idx']}], {c['bytes']}));")
    L.append("  }")
    L.append(f'  fprintf(stderr, "[exec] plan {idx} setup: buffers done\\n");')

    # 显存采样：主线程在每个组启动前采一次（单线程，避免 DTK 多线程切设备竞态）
    L.append(f"  float peak_free[{n_devs}]; size_t total_mem[{n_devs}];")
    L.append(f"  for (int d = 0; d < {n_devs}; d++) {{ peak_free[d] = 1e30f; total_mem[d] = 0; }}")
    # 探针模式用软件记账（hipFree 回内存池，hipMemGetInfo 不回涨）
    L.append(f"  double live[{n_devs}], peak_live[{n_devs}];")
    L.append(f"  for (int d = 0; d < {n_devs}; d++) {{ live[d] = 0.0; peak_live[d] = 0.0; }}")

    L.append("  auto t0 = std::chrono::steady_clock::now();")
    for gi, grp in enumerate(groups):
        dev = group_dev[gi]
        L.append(f"  hipSetDevice({dev});")
        L.append(f'  fprintf(stderr, "[exec] plan {idx} group {gi} dev {dev}\\n");')
        # 探针模式：按组延迟分配（组开始才 malloc），峰值反映真实生命周期
        L.append(f"  if (probe) {{")
        L.append(f"    hipSetDevice({dev});")
        for nid in grp["node_ids"]:
            i = node_ids.index(nid)
            sz = max(int(nodes[nid].get("out_bytes", 0)), 4)
            L.append(f"    if (out[{i}] == nullptr) {{ chk(hipMalloc(&out[{i}], {sz})); live[{dev}] += {sz}; }}")
            pb = int(nodes[nid].get("param_bytes", 0))
            if pb > 0:
                L.append(f"    if (param[{i}] == nullptr) {{ chk(hipMalloc(&param[{i}], {pb})); live[{dev}] += {pb}; }}")
        for ci in sorted(out_cross[gi]):
            c = cross[ci]
            L.append(f"    hipSetDevice({c['ddev']});")
            L.append(f"    if (recv[{ci}] == nullptr) {{ chk(hipMalloc(&recv[{ci}], {c['bytes']})); live[{c['ddev']}] += {c['bytes']}; }}")
        L.append(f"    hipSetDevice({dev});")
        L.append(f"    for (int d = 0; d < {n_devs}; d++) if (live[d] > peak_live[d]) peak_live[d] = live[d];")
        L.append("  }")
        L.append(f"  {{ size_t fb = 0, tb = 0; hipMemGetInfo(&fb, &tb); if ((float)fb < peak_free[{dev}]) peak_free[{dev}] = (float)fb; total_mem[{dev}] = tb; }}")
        # 同设备前驱：等组事件；跨设备输入：等拷贝事件
        same_preds = set()
        for nid in grp["node_ids"]:
            for e in edges:
                if e["dst"] == nid and node_group[e["src"]] != gi:
                    pg = node_group[e["src"]]
                    if group_dev[pg] == dev:
                        same_preds.add(pg)
        for pg in sorted(same_preds):
            L.append(f"  hipStreamWaitEvent(streams[{dev}], ev_g[{pg}], 0);")
        for ci in sorted(in_cross[gi]):
            # DTK 对跨设备流等待支持不稳：改为主机侧等拷贝完成事件
            L.append(f"  chk(hipEventSynchronize(ev_c[{ci}]));")
        # 组内 kernel
        for nid in grp["node_ids"]:
            nd = nodes[nid]
            i = node_ids.index(nid)
            op = nd["op_type"]
            if op == "input":
                continue
            ins = [e for e in edges if e["dst"] == nid]
            a = input_buf(nid, ins[0]) if ins else f"out[{i}]"
            if op == "matmul":
                sh = _shape(nd)
                m = int(sh.get("m", 1)); n = int(sh.get("n", 1)); k = int(sh.get("k", 1))
                b = f"param[{i}]"
                # 控制实验（EXEC_EMPTY_KERNELS=1）：kernel 换成空启动，保留组结构/同步/拷贝
                L.append(f"  if (empty) {{ empty_kernel<<<1, 1, 0, streams[{dev}]>>>(0); }} else {{")
                L.append(f"    chk_r(rocblas_set_stream(rb[{dev}], streams[{dev}]));")
                L.append(f"    {{ float alpha = 1.0f, beta = 0.0f;")
                L.append(f"      rocblas_sgemm(rb[{dev}], rocblas_operation_none, rocblas_operation_none, {m}, {n}, {k}, &alpha, {a}, {m}, {b}, {k}, &beta, out[{i}], {m}); }}")
                L.append("  }")
            else:
                # 逐元素算子的 n 取"输出与所有输入"的最小元素数，防止合成图尺寸不一致时越界
                n = _elem_n(nd)
                for e in ins:
                    n = min(n, in_elem(nid, e))
                n = max(n, 1)
                if op == "add":
                    b = input_buf(nid, ins[1]) if len(ins) > 1 else a
                    L.append(f"  if (empty) {{ empty_kernel<<<1, 1, 0, streams[{dev}]>>>(0); }} else {{ add_kernel<<<({n} + 255) / 256, 256, 0, streams[{dev}]>>>({a}, {b}, out[{i}], {n}); }}")
                elif op in ("layernorm", "softmax"):
                    kern = "layernorm_kernel" if op == "layernorm" else "softmax_kernel"
                    out_elem = max(int(nd.get("out_bytes", 4 * n)) // 4, 1)
                    in_min = min([in_elem(nid, e) for e in ins] or [n])
                    # 合成图可能尺寸不一致：保证 rows*n 不超过输入/输出实际元素数
                    rows = max(1, out_elem // n)
                    rows = min(rows, in_min // n)
                    if rows < 1 or rows * n > in_min:
                        n = max(1, min(in_min, out_elem))
                        rows = 1
                    L.append(f"  if (empty) {{ empty_kernel<<<1, 1, 0, streams[{dev}]>>>(0); }} else {{ {kern}<<<{rows}, 256, 256 * sizeof(float), streams[{dev}]>>>({a}, out[{i}], {n}, {rows}); }}")
                elif op == "gelu":
                    L.append(f"  if (empty) {{ empty_kernel<<<1, 1, 0, streams[{dev}]>>>(0); }} else {{ gelu_kernel<<<({n} + 255) / 256, 256, 0, streams[{dev}]>>>({a}, out[{i}], {n}); }}")
                elif op == "scale":
                    L.append(f"  if (empty) {{ empty_kernel<<<1, 1, 0, streams[{dev}]>>>(0); }} else {{ scale_kernel<<<({n} + 255) / 256, 256, 0, streams[{dev}]>>>({a}, 1.0f, out[{i}], {n}); }}")
                else:  # generic: 视为逐元素拷贝
                    L.append(f"  if (empty) {{ empty_kernel<<<1, 1, 0, streams[{dev}]>>>(0); }} else {{ pass_kernel<<<({n} + 255) / 256, 256, 0, streams[{dev}]>>>({a}, out[{i}], {n}); }}")
        L.append(f"  hipEventRecord(ev_g[{gi}], streams[{dev}]);")
        for ci in sorted(out_cross[gi]):
            c = cross[ci]
            src_i = node_ids.index(c["src"])
            L.append(f"  hipMemcpyAsync(recv[{ci}], out[{src_i}], {c['bytes']}, hipMemcpyDeviceToDevice, streams[{dev}]);")
            L.append(f"  hipEventRecord(ev_c[{ci}], streams[{dev}]);")
        # 内存探针：同步本组流后释放生命周期已结束的缓冲，峰值反映真实使用
        L.append(f"  if (probe) {{ chk(hipStreamSynchronize(streams[{dev}]));")
        for nid in grp["node_ids"]:
            if last_consumer.get(nid, -1) == gi:
                i = node_ids.index(nid)
                sz = max(int(nodes[nid].get("out_bytes", 0)), 4)
                L.append(f"    if (!out_freed[{i}]) {{ hipFree(out[{i}]); out_freed[{i}] = true; live[{dev}] -= {sz}; }}")
        for ci in sorted(in_cross[gi]):
            c = cross[ci]
            L.append(f"    if (!recv_freed[{ci}]) {{ hipFree(recv[{ci}]); recv_freed[{ci}] = true; live[{dev}] -= {c['bytes']}; }}")
        L.append("  }")

    L.append("  for (int d = 0; d < n_devs; d++) { hipDeviceSynchronize(); }")
    L.append("  auto t1 = std::chrono::steady_clock::now();")
    L.append("  double makespan = std::chrono::duration<double>(t1 - t0).count();")
    L.append(f'  printf("{{\\"plan\\":\\"{name}\\",\\"makespan_s\\":%.6f,\\"peak_mem\\":{{", makespan);')
    L.append(f"  for (int d = 0; d < {n_devs}; d++) {{")
    L.append('    printf("\\"%d\\":%.0f%s", d, probe ? peak_live[d] : (double)(total_mem[d] - peak_free[d]), d + 1 < n_devs ? "," : "");')
    L.append("  }")
    L.append('  printf("}}\\n"); fflush(stdout);')
    L.append("  for (int i = 0; i < NN; i++) { if (!out_freed[i]) hipFree(out[i]); if (param[i]) hipFree(param[i]); }")
    L.append("  for (int i = 0; i < NC; i++) { if (!recv_freed[i]) hipFree(recv[i]); hipEventDestroy(ev_c[i]); }")
    L.append("  for (int i = 0; i < NG; i++) { hipEventDestroy(ev_g[i]); }")
    L.append("  for (int d = 0; d < n_devs; d++) { hipStreamDestroy(streams[d]); }")
    L.append("}")
    return L


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plans", required=True, help="validation_plans.json")
    ap.add_argument("--out", required=True, help="输出 .cpp 路径")
    ap.add_argument("--n-gpus", type=int, default=4)
    args = ap.parse_args(argv)

    with open(args.plans, encoding="utf-8") as f:
        data = json.load(f)
    plans = data["plans"]

    lines = [HEADER]
    for i, entry in enumerate(plans):
        lines += _gen_plan(i, entry, args.n_gpus)
    lines.append("")
    lines.append(f"int main() {{")
    lines.append('  fprintf(stderr, "[exec] build: v8 (empty_kernel with dummy arg)\\n");')
    lines.append(f"  rocblas_handle rb[{args.n_gpus}];")
    lines.append(f"  for (int d = 0; d < {args.n_gpus}; d++) {{ hipSetDevice(d); chk_r(rocblas_create_handle(&rb[d])); }}")
    lines.append('  fprintf(stderr, "[exec] main: rocblas handles done\\n");')
    lines.append('  const char* only = getenv("EXEC_ONLY_PLAN");')
    lines.append(f"  if (only) {{ int p = atoi(only);")
    lines.append("    switch (p) {")
    for i in range(len(plans)):
        lines.append(f"      case {i}: run_plan_{i}(rb, {args.n_gpus}); break;")
    lines.append("    }")
    lines.append("    return 0;")
    lines.append("  }")
    for i in range(len(plans)):
        lines.append(f"  run_plan_{i}(rb, {args.n_gpus});")
    lines.append(f"  for (int d = 0; d < {args.n_gpus}; d++) {{ hipSetDevice(d); chk_r(rocblas_destroy_handle(rb[d])); }}")
    lines.append("  return 0;")
    lines.append("}")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"执行器已生成: {args.out} ({len(plans)} 个方案)")


if __name__ == "__main__":
    main()
