"""CPU FFN cost coverage, exhaustive placement and existing MCTS comparison.

Unmeasured costs are explicit exploration proxies. No GPU evidence or trusted
end-to-end latency is generated by this experiment.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path

from calibration.lightop_profile_calibration import ROOT
from cost_model.exact_search import exact_legal_search
from cost_model.ffn_placement_b1 import INPUT, OUTPUT, COMPUTE
from cost_model.fusion_kernel_profile import key_id
from cost_model.graph_analytic import analyze, assume, parameters
from cost_model.hardware_profile import AnalyticHardwareProfile, GroupCost, TransferCost
from cost_model.legal_search import legal_mcts_search
from cost_model.local_profile_search import build_case as activation_case, signature
from cost_model.native_stage_profile import NativeMeasuredFirstProfile
from cost_model.structural import StructuralCostModel
from simulator import FusionGroup, OpGraph, Plan

CONFIG = ROOT / "configs/ffn_profile_search.json"


def build_case(config):
    activation, measured, identity = activation_case()
    hardware = copy.deepcopy(measured.base.keys.hardware)
    # This is a declared Graph assumption, never the old eager launch scalar.
    hardware.launch_overhead = config["projection_graph_overhead_us"] / 1e6
    hardware.fusion_overhead = 0.
    source = measured.base.keys.graph
    full = OpGraph(name="layer0-ffn-cost-exploration", extra={"output_nodes": [OUTPUT]})
    for name in (INPUT, *COMPUTE, OUTPUT):
        full.add_node(copy.deepcopy(source.nodes[name]))
    full.edges = [copy.deepcopy(e) for e in source.edges if e.src in full.nodes and e.dst in full.nodes]
    for name in (INPUT, OUTPUT):
        full.nodes[name].op_type = "input"  # Zero-cost residency endpoints.
        full.nodes[name].flops = full.nodes[name].param_bytes = 0.
    for name in COMPUTE:
        if name in activation.nodes:
            full.nodes[name].extra = copy.deepcopy(activation.nodes[name].extra)
        # Future projection outputs are a planning contract, not new runtime observations.
        node = full.nodes[name]
        shape = node.extra["output_shape"]
        stride, strides = 1, []
        for size in reversed(shape):
            strides.insert(0, stride)
            stride *= size
        node.extra.update(layout="contiguous", strides=strides,
            layout_provenance={"kind": "graph_declaration", "source_id": "ffn_preallocated_output_planning_contract_v1"})
    search = OpGraph(name="layer0-ffn-five-compute-nodes", extra={"output_nodes": [COMPUTE[-1]]})
    search.nodes = {n: full.nodes[n] for n in COMPUTE}
    search.edges = [e for e in full.edges if e.src in search.nodes and e.dst in search.nodes]
    if len(full.edges) != 7:
        raise ValueError("FFN boundary/internal edges are incomplete")
    return search, full, hardware, measured, identity


def with_boundaries(plan):
    return Plan(name=plan.name, extra=copy.deepcopy(plan.extra), groups=[
        FusionGroup([INPUT], 0, {"pattern_id": "unfused"}),
        *copy.deepcopy(plan.groups), FusionGroup([OUTPUT], 0, {"pattern_id": "unfused"})])


class FFNProxyBase(AnalyticHardwareProfile):
    def __init__(self, hardware, measured, config, scenario):
        super().__init__(hardware)
        self.measured, self.config, self.scenario = measured, config, scenario
        assumption_path = ROOT / config["activation_assumptions_source"]
        assumptions = json.loads(assumption_path.read_text(encoding="utf-8"))["assumptions"]
        self.activation = {d: analyze(assume(parameters(hw.mem_bw, "historical copy proxy"), assumptions))
                           for d, hw in enumerate(hardware.devices)}

    def estimate_group(self, graph, group):
        if len(group.node_ids) == 1 and group.node_ids[0] in (INPUT, OUTPUT):
            return GroupCost(0., 0., 0., 0., 1., "logical_boundary")
        if len(group.node_ids) > 1:
            if tuple(group.node_ids) != tuple(COMPUTE[2:4]):
                raise ValueError("Unexpected fusion in fixed FFN experiment")
            if group.device == 0:
                return self.measured.base.estimate_group(self.measured.graph, group)
            value = self.activation[group.device]["arms"]["fused"]["duration_us"] / 1e6
            return GroupCost(value, value, 0., 0., .1, "analytic_ffn_fused_proxy",
                             ("activation_rates_and_graph_overhead:explicit_assumptions",))
        node = graph.nodes[group.node_ids[0]]
        if node.op_type == "matmul":
            cost = super().estimate_group(graph, group)
            scale = self.scenario["projection_scale"] * (self.scenario["gpu1_projection_scale"] if group.device == 1 else 1.)
            return GroupCost(cost.duration * scale, cost.compute_time * scale, cost.memory_time * scale,
                cost.launch_time * scale, .1, "analytic_ffn_gemm_proxy",
                ("gemm_rates:historical_proxy", "graph_overhead:explicit_assumption", "projection_layout:declared_not_observed"))
        stage = next(s for s in self.activation[group.device]["arms"]["native"]["stages"] if s["name"] == node.op_type)
        call = self.activation[group.device]["arms"]["native"]["graph_call_overhead_us"]
        value = (stage["duration_us"] + call) / 1e6
        return GroupCost(value, value, 0., 0., .1, "analytic_ffn_stage_proxy",
                         ("activation_rates_and_graph_overhead:explicit_assumptions",))

    def estimate_transfer(self, source, target, nbytes):
        cost = super().estimate_transfer(source, target, nbytes)
        return TransferCost(cost.duration * self.scenario["link_scale"], .1, "analytic_ffn_link_proxy",
            ("link_rates:historical_eager_proxy", "transport:per_edge_no_tensor_reuse_assumption"))


def build_report(config_path=CONFIG, seeds=(0, 1, 7)):
    from integration.lightop.silu_mul import adapter_registry
    config = json.loads(Path(config_path).read_text(encoding="utf-8"))
    search, full, hardware, measured, identity = build_case(config)
    registry = adapter_registry()
    model = StructuralCostModel(registry=registry)
    hardware_source = identity["fused_source"] + "/placed.json"
    input_hashes = {"hardware_snapshot_sha256": hashlib.sha256((ROOT / hardware_source).read_bytes()).hexdigest(),
        "activation_assumptions_sha256": hashlib.sha256((ROOT / config["activation_assumptions_source"]).read_bytes()).hexdigest()}
    scenarios = []
    for scenario in config["scenarios"]:
        assumption_id = key_id({"configuration": config, "scenario": scenario, "inputs": input_hashes})
        base = FFNProxyBase(hardware, measured, config, scenario)
        profile = NativeMeasuredFirstProfile(full, base, measured.store, measured.bindings)
        cache = {}
        def score(plan):
            key = signature(plan)
            if key not in cache:
                cache[key] = model.predict(full, with_boundaries(plan), profile)
            return cache[key].makespan
        exact = exact_legal_search(search, score, profile.n_devs, top_k=48,
            max_evaluations=48, registry=registry)
        if exact.search_space_size != 48:
            raise ValueError("FFN legal domain differs from the 32 Native + 16 Fused product")
        plans = []
        queries = {}
        for plan in exact.plans:
            estimate = cache[signature(plan)]
            placement = {n: g.device for g in plan.groups for n in g.node_ids}
            for group, cost in zip(with_boundaries(plan).groups, estimate.details["groups"]):
                if group.node_ids[0] in (INPUT, OUTPUT):
                    continue
                qid = "+".join(group.node_ids) + "@gpu" + str(group.device)
                measured_id = None
                if cost["source"] == "measured_group_kernel":
                    measured_id = identity["fused_kernel_key_id"]
                elif cost["source"] == "measured_native_isolated_stage":
                    measured_id = identity["native_stage_identities"][full.nodes[group.node_ids[0]].op_type]
                queries[qid] = {"nodes": group.node_ids, "device": group.device,
                    "source": cost["source"], "duration_us": cost["duration"] * 1e6,
                    "profile_identity_id": measured_id,
                    "assumption_id": None if measured_id else assumption_id,
                    "layout_context": "declared FFN output carrier; projection output not runtime captured"}
            plans.append({"plan_id": key_id(signature(plan)), "fused": any(len(g.node_ids) > 1 for g in plan.groups),
                "placement": placement, "cost_us": estimate.makespan * 1e6,
                "scoring_groups": [{"group_id": f"fg{i:04d}", "nodes": g.node_ids,
                                    "device": g.device, "pattern": g.extra["pattern_id"]}
                                   for i, g in enumerate(with_boundaries(plan).groups)],
                "profile_only": not any(g["source"].startswith("analytic_") for g in estimate.details["groups"]),
                "estimate": estimate.to_dict()})
        mcts = []
        for seed in seeds:
            cache = {}  # Each MCTS run queries its scorer independently of Exact.
            result = legal_mcts_search(search, score, profile.n_devs, registry=registry, iterations=128,
                                       rollouts=2, n_best=4, seed=seed)
            value = score(result[0])
            mcts.append({"seed": seed, "best_plan_id": key_id(signature(result[0])),
                "cost_us": value * 1e6, "cost_model_gap_us": (value - exact.optimal_score) * 1e6,
                "unique_candidates_scored": len(cache)})
        gpu0 = {"fused" if p["fused"] else "native": p for p in plans if set(p["placement"].values()) == {0}}
        native_by_placement = {tuple(sorted(p["placement"].items())): p for p in plans if not p["fused"]}
        pairs = [(p, native_by_placement[tuple(sorted(p["placement"].items()))]) for p in plans if p["fused"]]
        priority_diagnostic = None
        for fused_plan, native_plan in pairs:
            if fused_plan["cost_us"] >= native_plan["cost_us"]:
                continue
            # One legal ordering diagnostic, outside the 48 canonical plans.
            # It does not alter either search algorithm or the Exact domain.
            reordered = Plan(groups=[FusionGroup([node], native_plan["placement"][node],
                                                  {"pattern_id": "unfused"}) for node in COMPUTE])
            alternative = model.predict(full, with_boundaries(reordered), profile)
            priority_diagnostic = {"placement": native_plan["placement"],
                "native_canonical_us": native_plan["cost_us"], "fused_canonical_us": fused_plan["cost_us"],
                "native_gate_up_before_activation_us": alternative.makespan * 1e6,
                "same_cost_sources_and_placement": True, "added_to_search_space": False}
            break
        communication = {}
        for plan in plans:
            for transfer in plan["estimate"]["details"]["transfers"]:
                route = (transfer["bytes"], transfer["src_device"], transfer["dst_device"])
                communication[route] = {"tensor_bytes": route[0], "source_gpu": route[1],
                    "destination_gpu": route[2], "source": transfer["source"],
                    "duration_us": (transfer["end"] - transfer["start"]) * 1e6,
                    "assumption_id": assumption_id}
        scenarios.append({"assumptions": scenario, "best": plans[0], "plans": plans,
            "compute_queries": queries, "scoreable_plans": 48,
            "coverage": {"graph_compute_query_slots": len(queries),
                "measured_slots_under_declared_execution_contract": sum(q["profile_identity_id"] is not None for q in queries.values()),
                "analytic_compute_slots": sum(q["profile_identity_id"] is None for q in queries.values()),
                "communication_types": len(communication), "current_contract_measured_communication_types": 0},
            "communication_union": [communication[k] for k in sorted(communication)],
            "same_placement_fusion_pairs": {"count": len(pairs),
                "fused_lower_under_canonical_order": sum(f["cost_us"] < n["cost_us"] for f, n in pairs)},
            "priority_order_diagnostic": priority_diagnostic,
            "profile_only_plans": sum(p["profile_only"] for p in plans),
            "all_gpu0_comparison": {"native_us": gpu0["native"]["cost_us"], "fused_us": gpu0["fused"]["cost_us"],
                "fused_minus_native_us": gpu0["fused"]["cost_us"] - gpu0["native"]["cost_us"]}, "mcts": mcts})
    baseline = scenarios[0]["best"]
    return {"scope": "FFN CPU mixed-cost exploration, not GPU accuracy or joint-search benefit validation",
        "boundary_residency": {INPUT: 0, OUTPUT: 0}, "compute_nodes": list(COMPUTE),
        "identity": identity, "configuration": config,
        "search_parameters": {"exact_evaluations_per_scenario": 48, "mcts_iterations": 128,
                              "mcts_rollouts": 2, "mcts_seeds": list(seeds), "mcts_uses_exact_cache": False},
        "source_inputs": {"hardware_rate_snapshot": hardware_source, **input_hashes,
            "historical_eager_launch_us_not_used": measured.base.keys.hardware.launch_overhead * 1e6,
            "projection_graph_overhead_us_assumed": config["projection_graph_overhead_us"],
            "configuration_sha256": hashlib.sha256(Path(config_path).read_bytes()).hexdigest()},
        "scenario_results": scenarios,
        "sensitivity": [{"scenario": s["assumptions"]["name"],
            "best_changed": s["best"]["plan_id"] != baseline["plan_id"],
            "fusion_changed": s["best"]["fused"] != baseline["fused"],
            "placement_changed": s["best"]["placement"] != baseline["placement"]} for s in scenarios],
        "new_gpu_execution": False, "trusted_end_to_end_reference": None,
        "srop_enabled": False, "independent_regret": None,
        "execution_assumptions": ["Projection weights resident on each candidate device",
            "Existing canonical group priority; Exact does not enumerate alternative legal schedules",
            "Projection outputs preallocated contiguous by planning declaration, not captured runtime evidence",
            "Each cross-device edge transfers separately, including ingress/egress; no communication reuse proof",
            "Historical GEMM/copy/link rates and explicit Graph assumptions remain prediction proxies",
            "Exploration factors are not calibrated uncertainty bounds or independent validation data"]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = build_report()
    args.output.mkdir(parents=True, exist_ok=False)
    (args.output / "report.json").write_text(json.dumps(result, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    print(json.dumps({"scenarios": len(result["scenario_results"]),
        "baseline_best_us": result["scenario_results"][0]["best"]["cost_us"],
        "sensitivity": result["sensitivity"]}))


if __name__ == "__main__":
    main()
